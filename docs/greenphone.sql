
CREATE DATABASE IF NOT EXISTS greenphone
CHARACTER SET utf8mb4
COLLATE utf8mb4_unicode_ci;

USE greenphone;

-- =========================
-- 1. ROLE
-- =========================
CREATE TABLE `ROLE` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `NAME` VARCHAR(50) NOT NULL UNIQUE,
    `DESCRIPTION` VARCHAR(255),
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 2. USERS
-- =========================
CREATE TABLE `USERS` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `FULL_NAME` VARCHAR(100) NOT NULL,
    `EMAIL` VARCHAR(100) NOT NULL UNIQUE,
    `PASSWORD` VARCHAR(255) NOT NULL,
    `PHONE` VARCHAR(20) NOT NULL,
    `ADDRESS` VARCHAR(255),
    `ROLE_ID` BIGINT NOT NULL,
    `STATUS` VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_USERS_ROLE`
        FOREIGN KEY (`ROLE_ID`) REFERENCES `ROLE`(`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 3. BRAND
-- =========================
CREATE TABLE `BRAND` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `NAME` VARCHAR(100) NOT NULL UNIQUE,
    `LOGO_URL` VARCHAR(255),
    `STATUS` VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 4. PHONE
-- =========================
CREATE TABLE `PHONE` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `BRAND_ID` BIGINT NOT NULL,
    `NAME` VARCHAR(150) NOT NULL,
    `DESCRIPTION` TEXT,
    `SCREEN` VARCHAR(100),
    `OS` VARCHAR(100),
    `CHIP` VARCHAR(100),
    `REAR_CAMERA` VARCHAR(100),
    `FRONT_CAMERA` VARCHAR(100),
    `BATTERY` VARCHAR(100),
    `WARRANTY` VARCHAR(100),
    `STATUS` VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_PHONE_BRAND`
        FOREIGN KEY (`BRAND_ID`) REFERENCES `BRAND`(`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 5. OPTION (filter category: RAM/STORAGE/COLOR/FEATURE/...)
-- =========================
CREATE TABLE `OPTION` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `TYPE` VARCHAR(30) NOT NULL UNIQUE,
    `LABEL` VARCHAR(100) NOT NULL,
    `ENABLED` BOOLEAN NOT NULL DEFAULT TRUE,
    `MAX_ITEMS` INT NOT NULL DEFAULT 5,
    `SORT_ORDER` INT NOT NULL DEFAULT 0,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 6. OPTION_ITEM (individual values: 4GB, black, 5G)
-- =========================
CREATE TABLE `OPTION_ITEM` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `OPTION_ID` BIGINT NOT NULL,
    `VALUE` VARCHAR(50) NOT NULL,
    `HEX_COLOR` VARCHAR(7) NULL,
    `SORT_ORDER` INT NOT NULL DEFAULT 0,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_OPTION_ITEM_OPTION`
        FOREIGN KEY (`OPTION_ID`) REFERENCES `OPTION`(`ID`),
    CONSTRAINT `UQ_OPTION_ITEM_OPTION_VALUE`
        UNIQUE (`OPTION_ID`, `VALUE`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 7. PHONE_VARIANT
-- =========================
CREATE TABLE `PHONE_VARIANT` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `PHONE_ID` BIGINT NOT NULL,
    `RAM_ITEM_ID` BIGINT NOT NULL,
    `STORAGE_ITEM_ID` BIGINT NOT NULL,
    `COLOR_ITEM_ID` BIGINT NOT NULL,
    `PRICE` DECIMAL(12,2) NOT NULL,
    `DISCOUNT_PRICE` DECIMAL(12,2),
    `STOCK_QUANTITY` INT NOT NULL DEFAULT 0,
    `SKU` VARCHAR(100) UNIQUE,
    `STATUS` VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    `VERSION` BIGINT NOT NULL DEFAULT 0,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_PHONE_VARIANT_PHONE`
        FOREIGN KEY (`PHONE_ID`) REFERENCES `PHONE`(`ID`),
    CONSTRAINT `FK_PHONE_VARIANT_RAM`
        FOREIGN KEY (`RAM_ITEM_ID`) REFERENCES `OPTION_ITEM`(`ID`),
    CONSTRAINT `FK_PHONE_VARIANT_STORAGE`
        FOREIGN KEY (`STORAGE_ITEM_ID`) REFERENCES `OPTION_ITEM`(`ID`),
    CONSTRAINT `FK_PHONE_VARIANT_COLOR`
        FOREIGN KEY (`COLOR_ITEM_ID`) REFERENCES `OPTION_ITEM`(`ID`),

    CONSTRAINT `UQ_PHONE_VARIANT`
        UNIQUE (`PHONE_ID`, `RAM_ITEM_ID`, `STORAGE_ITEM_ID`, `COLOR_ITEM_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 6. PHONE_IMAGE
-- =========================
CREATE TABLE `PHONE_IMAGE` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `PHONE_ID` BIGINT NOT NULL,
    `IMAGE_URL` VARCHAR(255) NOT NULL,
    `IS_MAIN` BOOLEAN NOT NULL DEFAULT FALSE,
    `SORT_ORDER` INT NOT NULL DEFAULT 0,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_PHONE_IMAGE_PHONE`
        FOREIGN KEY (`PHONE_ID`) REFERENCES `PHONE`(`ID`)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 7. CART
-- =========================
CREATE TABLE `CART` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `USER_ID` BIGINT NOT NULL UNIQUE,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_CART_USERS`
        FOREIGN KEY (`USER_ID`) REFERENCES `USERS`(`ID`)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 8. CART_ITEM
-- =========================
CREATE TABLE `CART_ITEM` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `CART_ID` BIGINT NOT NULL,
    `PHONE_VARIANT_ID` BIGINT NOT NULL,
    `QUANTITY` INT NOT NULL DEFAULT 1,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_CART_ITEM_CART`
        FOREIGN KEY (`CART_ID`) REFERENCES `CART`(`ID`)
        ON DELETE CASCADE,

    CONSTRAINT `FK_CART_ITEM_PHONE_VARIANT`
        FOREIGN KEY (`PHONE_VARIANT_ID`) REFERENCES `PHONE_VARIANT`(`ID`),

    CONSTRAINT `UQ_CART_ITEM`
        UNIQUE (`CART_ID`, `PHONE_VARIANT_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 9. PROMOTION
-- =========================
CREATE TABLE `PROMOTION` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `CODE` VARCHAR(50) NOT NULL UNIQUE,
    `NAME` VARCHAR(100) NOT NULL,
    `DESCRIPTION` VARCHAR(255),
    `DISCOUNT_TYPE` VARCHAR(30) NOT NULL,
    `DISCOUNT_VALUE` DECIMAL(12,2) NOT NULL,
    `MAX_DISCOUNT_AMOUNT` DECIMAL(12,2),
    `MIN_ORDER_VALUE` DECIMAL(12,2),
    `QUANTITY` INT NOT NULL DEFAULT 0,
    `CLAIMED_QUANTITY` INT NOT NULL DEFAULT 0,
    `USED_QUANTITY` INT NOT NULL DEFAULT 0,
    `START_DATE` DATETIME NOT NULL,
    `END_DATE` DATETIME NOT NULL,
    `STATUS` VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 10. USER_PROMOTION
-- =========================
CREATE TABLE `USER_PROMOTION` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `USER_ID` BIGINT NOT NULL,
    `PROMOTION_ID` BIGINT NOT NULL,
    `STATUS` VARCHAR(30) NOT NULL DEFAULT 'AVAILABLE',
    `RECEIVED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `USED_AT` DATETIME,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_USER_PROMOTION_USERS`
        FOREIGN KEY (`USER_ID`) REFERENCES `USERS`(`ID`)
        ON DELETE CASCADE,

    CONSTRAINT `FK_USER_PROMOTION_PROMOTION`
        FOREIGN KEY (`PROMOTION_ID`) REFERENCES `PROMOTION`(`ID`),

    CONSTRAINT `UQ_USER_PROMOTION`
        UNIQUE (`USER_ID`, `PROMOTION_ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 11. ORDERS
-- =========================
CREATE TABLE `ORDERS` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `USER_ID` BIGINT NOT NULL,
    `USER_PROMOTION_ID` BIGINT UNIQUE,
    `RECEIVER_NAME` VARCHAR(100) NOT NULL,
    `RECEIVER_PHONE` VARCHAR(20) NOT NULL,
    `SHIPPING_ADDRESS` VARCHAR(255) NOT NULL,
    `TOTAL_AMOUNT` DECIMAL(12,2) NOT NULL,
    `DISCOUNT_AMOUNT` DECIMAL(12,2) DEFAULT 0,
    `FINAL_AMOUNT` DECIMAL(12,2) NOT NULL,
    `ORDER_STATUS` VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    `PAYMENT_STATUS` VARCHAR(30) NOT NULL DEFAULT 'UNPAID',
    `PAYMENT_METHOD` VARCHAR(30) NOT NULL,
    `NOTE` VARCHAR(255),
    `VERSION` BIGINT NOT NULL DEFAULT 0,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_ORDERS_USERS`
        FOREIGN KEY (`USER_ID`) REFERENCES `USERS`(`ID`),

    CONSTRAINT `FK_ORDERS_USER_PROMOTION`
        FOREIGN KEY (`USER_PROMOTION_ID`) REFERENCES `USER_PROMOTION`(`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 12. ORDER_DETAIL
-- =========================
CREATE TABLE `ORDER_DETAIL` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `ORDER_ID` BIGINT NOT NULL,
    `PHONE_VARIANT_ID` BIGINT NOT NULL,
    `PRODUCT_NAME` VARCHAR(150) NOT NULL,
    `RAM` VARCHAR(50) NOT NULL,
    `STORAGE` VARCHAR(50) NOT NULL,
    `COLOR` VARCHAR(50) NOT NULL,
    `UNIT_PRICE` DECIMAL(12,2) NOT NULL,
    `QUANTITY` INT NOT NULL,
    `SUBTOTAL` DECIMAL(12,2) NOT NULL,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_ORDER_DETAIL_ORDERS`
        FOREIGN KEY (`ORDER_ID`) REFERENCES `ORDERS`(`ID`)
        ON DELETE CASCADE,

    CONSTRAINT `FK_ORDER_DETAIL_PHONE_VARIANT`
        FOREIGN KEY (`PHONE_VARIANT_ID`) REFERENCES `PHONE_VARIANT`(`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 13. PAYMENT
-- =========================
CREATE TABLE `PAYMENT` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `ORDER_ID` BIGINT NOT NULL,
    `PAYMENT_PROVIDER` VARCHAR(50),
    `TRANSACTION_CODE` VARCHAR(100) UNIQUE,
    `AMOUNT` DECIMAL(12,2) NOT NULL,
    `PAID_AT` DATETIME,
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_PAYMENT_ORDERS`
        FOREIGN KEY (`ORDER_ID`) REFERENCES `ORDERS`(`ID`)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 14. REVIEW
-- =========================
CREATE TABLE `REVIEW` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `USER_ID` BIGINT NOT NULL,
    `PHONE_ID` BIGINT NOT NULL,
    `ORDER_DETAIL_ID` BIGINT NOT NULL UNIQUE,
    `RATING` INT NOT NULL,
    `CONTENT` TEXT,
    `STATUS` VARCHAR(30) NOT NULL DEFAULT 'SHOW',
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT `FK_REVIEW_USERS`
        FOREIGN KEY (`USER_ID`) REFERENCES `USERS`(`ID`),

    CONSTRAINT `FK_REVIEW_PHONE`
        FOREIGN KEY (`PHONE_ID`) REFERENCES `PHONE`(`ID`),

    CONSTRAINT `FK_REVIEW_ORDER_DETAIL`
        FOREIGN KEY (`ORDER_DETAIL_ID`) REFERENCES `ORDER_DETAIL`(`ID`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 15. BANNER
-- =========================
CREATE TABLE `BANNER` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `TITLE` VARCHAR(150) NOT NULL,
    `IMAGE_URL` VARCHAR(255) NOT NULL,
    `LINK_URL` VARCHAR(255),
    `STATUS` VARCHAR(30) NOT NULL DEFAULT 'ACTIVE',
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- =========================
-- 16. SETTINGS (key-value shop config)
-- =========================
CREATE TABLE `SETTINGS` (
    `ID` BIGINT AUTO_INCREMENT PRIMARY KEY,
    `SETTING_KEY` VARCHAR(50) NOT NULL UNIQUE,
    `SETTING_VALUE` TEXT NOT NULL,
    `DESCRIPTION` VARCHAR(255),
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `UPDATED_AT` DATETIME NULL DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
    `VERSION` BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

