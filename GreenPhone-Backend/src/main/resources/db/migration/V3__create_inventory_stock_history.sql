CREATE TABLE `inventory_stock_history` (
  `ID` bigint NOT NULL AUTO_INCREMENT,
  `PHONE_VARIANT_ID` bigint NOT NULL,
  `CHANGED_BY_USER_ID` bigint DEFAULT NULL,
  `CHANGED_BY_NAME` varchar(100) NOT NULL,
  `CHANGE_TYPE` varchar(30) NOT NULL,
  `QUANTITY_BEFORE` int NOT NULL,
  `QUANTITY_CHANGE` int NOT NULL,
  `QUANTITY_AFTER` int NOT NULL,
  `REASON` varchar(255) NOT NULL,
  `CREATED_AT` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `UPDATED_AT` datetime DEFAULT NULL ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`ID`),
  KEY `IDX_INVENTORY_HISTORY_VARIANT_CREATED` (`PHONE_VARIANT_ID`, `CREATED_AT`),
  KEY `IDX_INVENTORY_HISTORY_USER` (`CHANGED_BY_USER_ID`),
  CONSTRAINT `FK_INVENTORY_HISTORY_VARIANT` FOREIGN KEY (`PHONE_VARIANT_ID`) REFERENCES `phone_variant` (`ID`),
  CONSTRAINT `FK_INVENTORY_HISTORY_USER` FOREIGN KEY (`CHANGED_BY_USER_ID`) REFERENCES `users` (`ID`) ON DELETE SET NULL,
  CONSTRAINT `CK_INVENTORY_HISTORY_TYPE` CHECK (`CHANGE_TYPE` IN ('IMPORT', 'EXPORT', 'ADJUSTMENT')),
  CONSTRAINT `CK_INVENTORY_HISTORY_QUANTITY_AFTER` CHECK (`QUANTITY_AFTER` >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
